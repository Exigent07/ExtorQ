"""Kubernetes detection tests on the kind cluster ``extorq-lab`` (asset ``k8s:extorq-lab``).

Every kubectl call is pinned to the ExtorQ cluster: ``--kubeconfig
var/kube/extorq-lab-admin.kubeconfig --context kind-extorq-lab`` (never ``~/.kube/config``,
never another cluster such as ``motorq-security``) with a request timeout. The admin
identity is ``kubernetes-admin``, a human (certificate) identity, which is what the audit
rules expect for interactive misuse.

Objects are built as JSON documents in Python (no text templating) and created with
``kubectl create -f -``. Test pods are pinned to a node name that does not exist, so the
scheduler never places them: admission (what the rules detect) happens for real, but no
container of a test pod ever runs, privileged or not. Every object is deleted again and
its absence verified; the namespace fixture of K8S-005 is deleted after both phases.

Evidence: the kube-apiserver audit log, shipped by the OTel DaemonSet (``k8s.audit``,
seconds) and the inventory collector's diff (``k8s.api_inventory``, every 60 s).
"""

