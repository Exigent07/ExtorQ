class _ClusterTest(DetectionTest):
    def __init__(self, cluster: Cluster) -> None:
        self.cluster = cluster

    def _create_pod(
        self,
        cleanup: CleanupStack,
        name: str,
        namespace: str,
        *,
        privileged: bool,
        host_pid: bool = False,
        expect_denied: bool,
    ) -> str:
        cleanup.push(
            f"delete pod {namespace}/{name}", lambda: self.cluster.delete("pod", name, namespace)
        )
        result = self.cluster.create(
            pod_manifest(name, namespace, privileged=privileged, host_pid=host_pid)
        )
        message = display(result.stderr or result.stdout)
        if expect_denied:
            if result.ok:
                raise ActionFailed(
                    f"the API server ADMITTED the privileged pod {namespace}/{name}: Pod Security "
                    "is not enforced there (the pod is deleted by cleanup)"
                )
            if "violates PodSecurity" not in result.stderr:
                raise ActionFailed(f"create failed without a Pod Security denial: {message}")
            return f"denied by Pod Security admission (HTTP 403): {message}"
        if not result.ok:
            raise ActionFailed(f"the pod {namespace}/{name} was not admitted: {message}")
        return f"admitted (HTTP 201), pinned to a node that does not exist: {message}"


