def pod_manifest(
    name: str, namespace: str, *, privileged: bool = False, host_pid: bool = False
) -> dict[str, Any]:
    """A test pod: identical for the positive and the negative except the risky settings."""
    validate_artefact_name(name)
    if privileged:
        security: dict[str, Any] = {"privileged": True}
    else:
        security = {
            "allowPrivilegeEscalation": False,
            "capabilities": {"drop": ["ALL"]},
            "readOnlyRootFilesystem": True,
            "runAsNonRoot": True,
            "runAsUser": 65534,
            "seccompProfile": {"type": "RuntimeDefault"},
        }
    spec: dict[str, Any] = {
        "automountServiceAccountToken": False,
        "restartPolicy": "Never",
        "terminationGracePeriodSeconds": 0,
        "nodeSelector": dict(UNSCHEDULABLE),
        "containers": [
            {
                "name": "worker",
                "image": TEST_IMAGE,
                "imagePullPolicy": "IfNotPresent",
                "command": ["sleep", "300"],
                "securityContext": security,
            }
        ],
    }
    if host_pid:
        spec["hostPID"] = True
    return {
        "apiVersion": "v1",
        "kind": "Pod",
        "metadata": {"name": name, "namespace": namespace},
        "spec": spec,
    }


def service_account_manifest(name: str, namespace: str) -> dict[str, Any]:
    validate_artefact_name(name)
    return {
        "apiVersion": "v1",
        "kind": "ServiceAccount",
        "metadata": {"name": name, "namespace": namespace},
        # No token is mounted or created: nobody can authenticate as this account.
        "automountServiceAccountToken": False,
    }


def cluster_admin_binding_manifest(name: str, sa_namespace: str) -> dict[str, Any]:
    validate_artefact_name(name)
    return {
        "apiVersion": "rbac.authorization.k8s.io/v1",
        "kind": "ClusterRoleBinding",
        "metadata": {"name": name},
        "roleRef": {
            "apiGroup": "rbac.authorization.k8s.io",
            "kind": "ClusterRole",
            "name": "cluster-admin",
        },
        "subjects": [{"kind": "ServiceAccount", "name": name, "namespace": sa_namespace}],
    }


def view_binding_manifest(name: str, namespace: str) -> dict[str, Any]:
    validate_artefact_name(name)
    return {
        "apiVersion": "rbac.authorization.k8s.io/v1",
        "kind": "RoleBinding",
        "metadata": {"name": name, "namespace": namespace},
        "roleRef": {"apiGroup": "rbac.authorization.k8s.io", "kind": "ClusterRole", "name": "view"},
        "subjects": [{"kind": "ServiceAccount", "name": name, "namespace": namespace}],
    }


def namespace_manifest(name: str) -> dict[str, Any]:
    """A namespace WITHOUT Pod Security labels (the cluster default does not enforce)."""
    validate_artefact_name(name)
    return {"apiVersion": "v1", "kind": "Namespace", "metadata": {"name": name}}


# ── cluster access ─────────────────────────────────────────────────────────────────────


class Cluster:
    def __init__(self, root: Path) -> None:
        self.root = root
        self.kubeconfig = root / ADMIN_KUBECONFIG

    def kubectl_argv(self, *args: str) -> list[str]:
        """kubectl argv pinned to the ExtorQ cluster (kubeconfig, context, request timeout)."""
        return [
            "kubectl",
            "--kubeconfig",
            str(self.kubeconfig),
            "--context",
            CONTEXT,
            "--request-timeout=20s",
            *args,
        ]

    def kubectl(
        self,
        *args: str,
        input_text: str | None = None,
        capture_stdout: bool = True,
        timeout: float = 60,
    ) -> ProcResult:
        return run(
            self.kubectl_argv(*args),
            timeout=timeout,
            input_text=input_text,
            capture_stdout=capture_stdout,
            what="kubectl",
        )

    def create(self, manifest: Mapping[str, Any]) -> ProcResult:
        return self.kubectl("create", "-f", "-", "-o", "name", input_text=json.dumps(manifest))

    def exists(self, kind: str, name: str, namespace: str | None = None) -> bool:
        args = ["get", kind, name, "--ignore-not-found", "-o", "name"]
        if namespace:
            args += ["-n", namespace]
        result = self.kubectl(*args)
        if not result.ok:
            raise ActionFailed(f"kubectl get {kind} {name}: {display(result.stderr)}")
        return bool(result.stdout.strip())

    def delete(self, kind: str, name: str, namespace: str | None = None, *, wait: int = 90) -> str:
        """Delete one named test object and verify it is gone (cleanup step)."""
        validate_artefact_name(name)
        args = ["delete", kind, name, "--ignore-not-found", "--wait=true", f"--timeout={wait}s"]
        if namespace:
            args += ["-n", namespace]
        result = self.kubectl(*args, timeout=wait + 30)
        if not result.ok:
            raise ActionFailed(f"kubectl delete {kind} {name}: {display(result.stderr)}")
        deadline = time.monotonic() + wait
        while self.exists(kind, name, namespace):
            if time.monotonic() > deadline:
                raise ActionFailed(f"{kind} {name} still exists after {wait}s")
            time.sleep(2)  # plain sleep: cleanup must finish even after Ctrl-C
        return "deleted (verified absent)"

    def lab_portal_pod(self) -> str:
        result = self.kubectl(
            "get",
            "pods",
            "-n",
            APPS_NS,
            "-l",
            LAB_PORTAL_SELECTOR,
            "--field-selector=status.phase=Running",
            "-o",
            "jsonpath={.items[*].metadata.name}",
        )
        names = [n for n in result.stdout.split() if _DNS_LABEL_RE.fullmatch(n)]
        if not result.ok or not names:
            raise PreconditionFailed(f"no running lab-portal pod in {APPS_NS}")
        return sorted(names)[0]

    def check(self, _ctx: TestContext) -> list[StepResult]:
        checks = [
            StepResult("kubectl on PATH", which("kubectl") is not None, "kubectl"),
            StepResult("kind on PATH", which("kind") is not None, "kind"),
            StepResult(
                f"file {ADMIN_KUBECONFIG}",
                self.kubeconfig.is_file(),
                "present" if self.kubeconfig.is_file() else "missing: run `make kind-up`",
            ),
        ]
        if not all(c.ok for c in checks):
            return checks
        clusters = run(["kind", "get", "clusters"], timeout=30).stdout.split()
        checks.append(
            StepResult(
                f"kind cluster {CLUSTER}",
                CLUSTER in clusters,
                "present" if CLUSTER in clusters else "missing: run `make kind-up`",
            )
        )
        if not checks[-1].ok:
            return checks
        ready = self.kubectl("get", "--raw", "/readyz")
        checks.append(
            StepResult(
                f"API server of {CLUSTER} ({CONTEXT})",
                ready.ok and ready.stdout.strip() == "ok",
                "ready" if ready.ok else display(ready.stderr),
            )
        )
        for namespace in (RESTRICTED_NS, APPS_NS):
            present = ready.ok and self.kubectl("get", "namespace", namespace, "-o", "name").ok
            checks.append(
                StepResult(f"namespace {namespace}", present, "present" if present else "missing")
            )
        return checks

    def audit_flowing(self, ctx: TestContext) -> list[StepResult]:
        """The audit pipeline (OTel DaemonSet -> gateway) delivered events recently.

        The inventory collector lists the API every minute and those reads are audited, so
        an empty quarter of an hour means the pipeline, not the cluster, is quiet.
        """
        now = ctx.clock.now()
        try:
            events = ctx.api.events(
                asset_id=ASSET.asset_id,
                event_type="k8s.api.request",
                since=now - timedelta(minutes=15),
                until=now + timedelta(minutes=1),
                source_type="k8s.audit",
                limit=1,
            )
        except ApiError as exc:
            return [StepResult("k8s.audit telemetry (last 15 min)", False, str(exc))]
        return [
            StepResult(
                "k8s.audit telemetry (last 15 min)",
                bool(events),
                "flowing"
                if events
                else "none: check the OTel DaemonSet (infra/kind/kind.sh status)",
            )
        ]

    def sweep(self, _ctx: TestContext) -> list[StepResult]:
        """Delete leftover ``extorq-test-<6 hex>`` objects of interrupted runs."""
        results: list[StepResult] = []
        targets: list[tuple[str, str | None]] = [
            ("clusterrolebindings", None),
            ("namespaces", None),
            ("pods", RESTRICTED_NS),
            ("pods", APPS_NS),
            ("rolebindings", APPS_NS),
            ("serviceaccounts", APPS_NS),
        ]
        for kind, namespace in targets:
            args = ["get", kind, "-o", "jsonpath={.items[*].metadata.name}"]
            if namespace:
                args += ["-n", namespace]
            listing = self.kubectl(*args)
            if not listing.ok:
                results.append(StepResult(f"list {kind}", False, display(listing.stderr)))
                continue
            for name in listing.stdout.split():
                try:
                    validate_artefact_name(name)
                except ValueError:
                    continue  # never touch objects the suite did not create
                where = f"{namespace}/" if namespace else ""
                try:
                    detail = self.delete(kind, name, namespace)
                    results.append(StepResult(f"delete {kind} {where}{name}", True, detail))
                except ActionFailed as exc:
                    results.append(StepResult(f"delete {kind} {where}{name}", False, str(exc)))
        if not results:
            results.append(StepResult("cluster leftovers", True, "none found"))
        return results


def audit_request(
    description: str,
    *,
    resource: str,
    name: str | None = None,
    verb: str | None = None,
    namespace: str | None = None,
    code: int | None = None,
    message_contains: str | None = None,
    cluster_wide: bool = False,
) -> TelemetryExpectation:
    equals: list[tuple[str, str | int]] = [("k8s_resource", resource)]
    if name is not None:
        equals.append(("k8s_object_name", name))
    if verb is not None:
        equals.append(("k8s_verb", verb))
    if namespace is not None:
        equals.append(("k8s_namespace", namespace))
    if code is not None:
        equals.append(("k8s_response_code", code))
    return TelemetryExpectation(
        description,
        "k8s.api.request",
        equals=tuple(equals),
        contains=(("message", message_contains),) if message_contains else (),
        is_null=("k8s_namespace",) if cluster_wide else (),
        source_type="k8s.audit",
    )


