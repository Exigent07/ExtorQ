class PrivilegedPodAdmittedTest(_ClusterTest):
    spec = TestSpec(
        test_id="kubernetes.k8s-005",
        asset=ASSET,
        rule_id="K8S-005",
        title="Privileged pod admitted in a namespace without Pod Security enforcement",
        positive=(
            "Create namespace extorq-test-<id> without Pod Security labels, then a privileged "
            "pod in it: admitted (201)."
        ),
        negative="An unprivileged, restricted-compliant pod in the same namespace.",
        cleanup="Delete both pods, then the namespace; verify they are gone.",
        expected_alert="K8S-005 on k8s:extorq-lab for the admitted privileged pod.",
        safety=(
            "Both pods are pinned to a node that does not exist, so the scheduler never places "
            "them and the privileged container never runs."
        ),
        source=AUDIT,
        # K8S-005 groups by namespace and every run uses a new namespace.
        fresh_group=True,
    )

    def __init__(self, cluster: Cluster) -> None:
        super().__init__(cluster)
        self.namespace: str | None = None

    def setup(self, ctx: TestContext, cleanup: CleanupStack) -> list[str]:
        name = ctx.new_name()
        cleanup.push(
            f"delete namespace {name}", lambda: self.cluster.delete("namespace", name, wait=180)
        )
        result = self.cluster.create(namespace_manifest(name))
        if not result.ok:
            raise ActionFailed(f"create namespace {name}: {display(result.stderr)}")
        self.namespace = name
        return [f"namespace {name} (no Pod Security labels)"]

    def _ns(self) -> str:
        if self.namespace is None:
            raise ActionFailed("the test namespace was not created")
        return self.namespace

    def positive(self, ctx: TestContext, cleanup: CleanupStack) -> ActionRecord:
        namespace, name = self._ns(), ctx.new_name()
        detail = self._create_pod(cleanup, name, namespace, privileged=True, expect_denied=False)
        return ActionRecord(
            f"privileged pod {namespace}/{name} admitted",
            details=[detail],
            artefacts=[f"pod {namespace}/{name}"],
            telemetry=[
                audit_request(
                    "audit log recorded the admitted privileged create",
                    resource="pods",
                    name=name,
                    verb="create",
                    namespace=namespace,
                    code=201,
                )
            ],
            artefact_hint=name,
        )

    def negative(self, ctx: TestContext, cleanup: CleanupStack) -> ActionRecord:
        namespace, name = self._ns(), ctx.new_name()
        detail = self._create_pod(cleanup, name, namespace, privileged=False, expect_denied=False)
        return ActionRecord(
            f"unprivileged pod {namespace}/{name} admitted",
            details=[detail],
            artefacts=[f"pod {namespace}/{name}"],
            telemetry=[
                audit_request(
                    "audit log recorded the admitted unprivileged create",
                    resource="pods",
                    name=name,
                    verb="create",
                    namespace=namespace,
                    code=201,
                )
            ],
        )


class ClusterWebLoginTest(_ClusterTest):
    spec = TestSpec(
        test_id="kubernetes.app-001",
        asset=ASSET,
        rule_id="APP-001",
        title="Burst of failed logins to the in-cluster web application",
        positive=(
            "6 failed POST /login for lab-admin with random wrong passwords through the NodePort "
            "127.0.0.1:8089."
        ),
        negative="One successful login with the demo password (read from its 0600 file).",
        cleanup="Nothing to remove (one portal session expires on its own).",
        expected_alert="APP-001 on k8s:extorq-lab, variant guessing, user lab-admin.",
        safety="Wrong passwords are random; the demo password is sent once and never printed.",
        source=CONTAINER_LOG,
    )

    def preconditions(self, ctx: TestContext) -> list[StepResult]:
        password_file = ctx.root / DEMO_PASSWORD_FILE
        if not password_file.is_file():
            raise PreconditionFailed(f"{DEMO_PASSWORD_FILE} is missing (run `make kind-up`)")
        status = request(f"{NODEPORT_BASE}/healthz")
        if status != 200:
            raise PreconditionFailed(f"{NODEPORT_BASE}/healthz answered {status}")
        return [StepResult("lab-portal NodePort", True, f"{NODEPORT_BASE} healthy")]

    def positive(self, ctx: TestContext, cleanup: CleanupStack) -> ActionRecord:
        statuses = failed_logins(NODEPORT_BASE, 6)
        if any(status != 401 for status in statuses):
            raise ActionFailed(f"failed logins were answered {statuses} (expected 401 each)")
        return ActionRecord(
            "6 failed logins for lab-admin via the NodePort",
            details=[f"POST /login x6 -> {statuses}"],
            telemetry=[
                TelemetryExpectation(
                    "lab-portal container reported 6 failed logins",
                    "app.auth.login_failed",
                    actor=DEMO_USER,
                    source_type="k8s.container_log",
                    min_count=6,
                )
            ],
            artefact_hint=DEMO_USER,
        )

    def negative(self, ctx: TestContext, cleanup: CleanupStack) -> ActionRecord:
        password = (ctx.root / DEMO_PASSWORD_FILE).read_text(encoding="utf-8").strip()
        status = login(NODEPORT_BASE, DEMO_USER, password)
        del password
        if status != 200:
            raise ActionFailed(f"the demo login was answered {status} (expected 200)")
        return ActionRecord(
            "1 successful login of lab-admin via the NodePort",
            details=["POST /login -> 200"],
            telemetry=[
                TelemetryExpectation(
                    "lab-portal container reported the successful login",
                    "app.auth.login_succeeded",
                    actor=DEMO_USER,
                    source_type="k8s.container_log",
                )
            ],
        )


def build_suite(root: Path) -> AssetSuite:
    cluster = Cluster(root)
    tests: Sequence[DetectionTest] = (
        PrivilegedPodDeniedTest(cluster),
        RiskyRbacTest(cluster),
        ExecIntoPodTest(cluster),
        SecretEnumerationTest(cluster),
        PrivilegedPodAdmittedTest(cluster),
        ClusterWebLoginTest(cluster),
    )
    return AssetSuite(
        asset=ASSET,
        tests=list(tests),
        check=cluster.check,
        sweep=cluster.sweep,
        collector_ids=(INVENTORY_COLLECTOR,),
        telemetry_check=cluster.audit_flowing,
    )
