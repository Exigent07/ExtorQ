"""nginx JSON access lines and lab-portal contract lines -> HTTP/application events.

Both arrive through journald. Their claimed identity is verified with the
sender's systemd unit (``_SYSTEMD_UNIT`` comes from the cgroup; only root can
place a process in ``nginx.service`` or ``lab-portal.service``).

Every value is attacker-influenced (paths, user agents, submitted user names)
and is type-checked, bounded and sanitised. ``http.request_id`` is only set for
ids genuinely propagated by nginx (``$request_id``); an id generated by the app
itself is kept in ``attributes.app_request_id`` because it correlates nothing.

Source network context: the VM uses QEMU user-mode networking, so every
connection that originates on the Mac (simulations, curl) appears to nginx as
``10.0.2.2`` (the SLIRP gateway). ``network.src_ip`` reports exactly what the
source logged and is not "corrected".
"""

from __future__ import annotations

import ipaddress
import json
import math
import re
from typing import Any
from urllib.parse import urlsplit

from extorq.contracts import (
    Actor,
    ActorType,
    HttpInfo,
    Network,
    Outcome,
    SecurityEvent,
    Severity,
    SourceType,
)

from extorq_collectors.linux.common import (
    ParseContext,
    build_event,
    clean,
    from_epoch_s,
    parse_rfc3339,
)
from extorq_collectors.linux.journal import (
    JournalEntry,
    Trust,
    forged_identity_event,
    trust_unit,
)

PARSER_NGINX = "linux-nginx-json"
PARSER_APP = "lab-portal-json"

_REQUEST_ID = re.compile(r"^[0-9a-f]{32}$")
_APP_REQUEST_ID = re.compile(r"^[A-Za-z0-9._-]{8,128}$")
_METHOD = re.compile(r"^[A-Z]{1,16}$")
_APP_EVENTS = {
    "auth.login_failed": ("app.auth.login_failed", Outcome.FAILURE),
    "auth.login_succeeded": ("app.auth.login_succeeded", Outcome.SUCCESS),
    "authz.denied": ("app.authz.denied", Outcome.DENIED),
    "http.request": ("http.request", None),
}
_LEVEL_SEVERITY = {"info": Severity.INFO, "warning": Severity.MEDIUM, "error": Severity.HIGH}
APP_UNIT = "lab-portal.service"
NGINX_UNIT = "nginx.service"


def _ip(value: Any) -> str | None:
    if not isinstance(value, str) or len(value) > 64:
        return None
    try:
        return str(ipaddress.ip_address(value))
    except ValueError:
        return None


def _int(value: Any, low: int, high: int) -> int | None:
    if isinstance(value, bool) or not isinstance(value, int):
        return None
    return value if low <= value <= high else None


def _float(value: Any, low: float, high: float) -> float | None:
    if isinstance(value, bool) or not isinstance(value, int | float):
        return None
    number = float(value)
    if math.isnan(number) or math.isinf(number) or not low <= number <= high:
        return None
    return number


def _route(value: Any) -> str | None:
    """Path only: strip query string and fragment defensively, bound length."""
    if not isinstance(value, str) or not value:
        return None
    try:
        path = urlsplit(value).path if ("?" in value or "#" in value) else value
    except ValueError:
        path = value.split("?", 1)[0].split("#", 1)[0]
    return clean(path, 2048)


def _http_outcome(status: int | None) -> Outcome:
    if status is None:
        return Outcome.UNKNOWN
    if status in (401, 403):
        return Outcome.DENIED
    return Outcome.SUCCESS if status < 400 else Outcome.FAILURE


def _load_json(message: str) -> dict[str, Any] | None:
    if not message.startswith("{") or len(message) > 16384:
        return None
    try:
        obj = json.loads(message)
    except ValueError:
        return None
    return obj if isinstance(obj, dict) else None


def parse_nginx_access(entry: JournalEntry, ctx: ParseContext) -> list[SecurityEvent]:
    trust = trust_unit(entry, NGINX_UNIT)
    if trust is Trust.MISMATCH:
        return [forged_identity_event(entry, ctx, "nginx_access")]
    obj = _load_json(entry.message)
    if obj is None:
        return []
    status = _int(obj.get("status"), 100, 599)
    method_raw = obj.get("request_method")
    method = method_raw if isinstance(method_raw, str) and _METHOD.match(method_raw) else None
    route = _route(obj.get("uri"))
    request_id_raw = obj.get("request_id")
    request_id = request_id_raw if isinstance(request_id_raw, str) and \
        _REQUEST_ID.match(request_id_raw) else None
    user_agent = clean(obj.get("http_user_agent"), 2048) if obj.get("http_user_agent") else None
    request_time = _float(obj.get("request_time"), 0.0, 86400.0)
    msec = _float(obj.get("msec"), 1.0e9, 1.0e10)
    event_time = from_epoch_s(msec) if msec is not None else (
        parse_rfc3339(str(obj.get("time_iso8601", ""))) or entry.time)
    src_ip = _ip(obj.get("remote_addr"))
    attrs: dict[str, Any] = {"time_iso8601": clean(obj.get("time_iso8601"), 64),
                             "boot_id": entry.boot_id}
    if trust is not Trust.VERIFIED:
        attrs["source_verified"] = False
    return [build_event(
        ctx,
        event_type="http.request",
        source_type=SourceType.LINUX_NGINX,
        native_key=entry.cursor,
        source_native_id=entry.cursor,
        event_time=event_time,
        parser=PARSER_NGINX,
        action="http.request",
        outcome=_http_outcome(status),
        http=HttpInfo(
            method=method,
            route=route,
            status_code=status,
            request_id=request_id,
            user_agent=user_agent,
            host=clean(obj.get("host"), 256),
            duration_ms=round(request_time * 1000.0, 3) if request_time is not None else None,
            bytes_sent=_int(obj.get("body_bytes_sent"), 0, 2**53),
        ),
        network=Network(src_ip=src_ip, protocol="tcp", direction="inbound") if src_ip else None,
        message=f"{method or '?'} {route or '?'} -> {status if status is not None else '?'}",
        raw=entry.message,
        attributes=attrs,
        sim_texts=(user_agent, route),
    )]


def parse_lab_portal(entry: JournalEntry, ctx: ParseContext) -> list[SecurityEvent]:
    trust = trust_unit(entry, APP_UNIT)
    if trust is Trust.MISMATCH:
        return [forged_identity_event(entry, ctx, "lab-portal")]
    obj = _load_json(entry.message)
    if obj is None or obj.get("service") != "lab-portal":
        return []  # startup diagnostics (stderr) share the stream; not events
    mapped = _APP_EVENTS.get(obj.get("event"))  # type: ignore[arg-type]
    if mapped is None:
        return []
    event_type, outcome = mapped
    status = _int(obj.get("status"), 100, 599)
    if outcome is None:
        outcome = _http_outcome(status)
    user = clean(obj.get("user"), 256) if isinstance(obj.get("user"), str) else None
    rid = obj.get("request_id")
    rid_source = obj.get("request_id_source")
    request_id = rid if isinstance(rid, str) and _APP_REQUEST_ID.match(rid) else None
    propagated = rid_source == "propagated" and request_id is not None
    method_raw = obj.get("method")
    method = method_raw if isinstance(method_raw, str) and _METHOD.match(method_raw) else None
    route = _route(obj.get("route"))
    user_agent = clean(obj.get("user_agent"), 2048) if obj.get("user_agent") else None
    duration = _float(obj.get("duration_ms"), 0.0, 86_400_000.0)
    src_ip = _ip(obj.get("src_ip"))
    level = obj.get("level") if obj.get("level") in _LEVEL_SEVERITY else None
    reason = clean(obj.get("reason"), 128) if isinstance(obj.get("reason"), str) else None
    attrs: dict[str, Any] = {
        "reason": reason,
        "request_id_source": rid_source if rid_source in ("propagated", "generated") else None,
        "app_request_id": request_id if not propagated else None,
        "service": "lab-portal",
        "level": level,
        "boot_id": entry.boot_id,
    }
    if trust is not Trust.VERIFIED:
        attrs["source_verified"] = False
    action = obj.get("event") if isinstance(obj.get("event"), str) else None
    return [build_event(
        ctx,
        event_type=event_type,
        source_type=SourceType.LINUX_APP,
        native_key=entry.cursor,
        source_native_id=entry.cursor,
        event_time=parse_rfc3339(str(obj.get("ts", ""))) or entry.time,
        parser=PARSER_APP,
        action=action,
        outcome=outcome,
        severity_hint=_LEVEL_SEVERITY.get(level) if level else None,
        actor=Actor(type=ActorType.USER, name=user) if user else None,
        http=HttpInfo(method=method, route=route, status_code=status,
                      request_id=request_id if propagated else None,
                      user_agent=user_agent, duration_ms=duration),
        network=Network(src_ip=src_ip, protocol="tcp", direction="inbound") if src_ip else None,
        message=(f"lab-portal {action}: user={user or '-'} status={status} "
                 f"reason={reason or '-'}"),
        raw=entry.message,
        attributes=attrs,
        sim_texts=(user, user_agent, route),
    )]
