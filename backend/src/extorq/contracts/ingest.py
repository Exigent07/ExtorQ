"""Ingestion wire contract (schema 1.0).

``POST /v1/ingest`` accepts an :class:`IngestBatch`. The batch envelope is
validated strictly; ``records`` are validated *individually* so one malformed
record is quarantined without rejecting its neighbours.

Durability contract (docs/data-flow.md): a 202 response means every accepted
record and the batch idempotency key were committed to the gateway's durable
SQLite spool (WAL, synchronous=FULL) before the response was sent. Re-sending
the same ``batch_id`` returns the original result (``replayed=true``).
Delivery to ClickHouse is at-least-once; logical duplicates collapse by
deterministic identity. ExtorQ does NOT claim exactly-once semantics.
"""

from __future__ import annotations

from enum import StrEnum
from typing import Annotated, Any, Literal

from pydantic import Field, TypeAdapter

from extorq.contracts.asset import Asset, InventoryItem
from extorq.contracts.common import (
    SCHEMA_VERSION,
    ContractModel,
    Identifier,
    MediumStr,
    SchemaVersion,
    UtcDatetime,
)
from extorq.contracts.event import SecurityEvent
from extorq.contracts.finding import PostureFinding
from extorq.contracts.health import CollectorHealth
from extorq.contracts.identity import canonical_json, iso_utc, stable_id
from extorq.contracts.scan import ScanRun
from extorq.contracts.service import Service, ServiceInstance

MAX_BATCH_RECORDS = 1000
MAX_BODY_BYTES = 4 * 1024 * 1024
MAX_RECORD_BYTES = 64 * 1024
#: Periodic instance refreshes pass dedup at most once per bucket (see record_identity).
INSTANCE_REFRESH_BUCKET_SECONDS = 600


class RecordKind(StrEnum):
    EVENT = "event"
    ASSET = "asset"
    INVENTORY_ITEM = "inventory_item"
    FINDING = "finding"
    SCAN_RUN = "scan_run"
    COLLECTOR_HEALTH = "collector_health"
    SERVICE = "service"
    SERVICE_INSTANCE = "service_instance"


class EventRecord(ContractModel):
    kind: Literal["event"] = "event"
    data: SecurityEvent


class AssetRecord(ContractModel):
    kind: Literal["asset"] = "asset"
    data: Asset


class InventoryItemRecord(ContractModel):
    kind: Literal["inventory_item"] = "inventory_item"
    data: InventoryItem


class FindingRecord(ContractModel):
    kind: Literal["finding"] = "finding"
    data: PostureFinding


class ScanRunRecord(ContractModel):
    kind: Literal["scan_run"] = "scan_run"
    data: ScanRun


class CollectorHealthRecord(ContractModel):
    kind: Literal["collector_health"] = "collector_health"
    data: CollectorHealth


class ServiceRecord(ContractModel):
    kind: Literal["service"] = "service"
    data: Service


class ServiceInstanceRecord(ContractModel):
    kind: Literal["service_instance"] = "service_instance"
    data: ServiceInstance


IngestRecord = Annotated[
    EventRecord
    | AssetRecord
    | InventoryItemRecord
    | FindingRecord
    | ScanRunRecord
    | CollectorHealthRecord
    | ServiceRecord
    | ServiceInstanceRecord,
    Field(discriminator="kind"),
]

INGEST_RECORD_ADAPTER: TypeAdapter[IngestRecord] = TypeAdapter(IngestRecord)


class IngestBatch(ContractModel):
    schema_version: SchemaVersion = SCHEMA_VERSION
    #: Idempotency key generated by the producer's outbox (UUID4 hex or canonical).
    batch_id: Annotated[str, Field(pattern=r"^[0-9a-f]{32}$|^[0-9a-f-]{36}$")]
    producer_id: Identifier
    sent_at: UtcDatetime
    #: Raw records: validated one-by-one with INGEST_RECORD_ADAPTER.
    records: list[dict[str, Any]] = Field(min_length=1, max_length=MAX_BATCH_RECORDS)


class QuarantineNotice(ContractModel):
    index: int = Field(ge=0)
    reason: MediumStr


class IngestResult(ContractModel):
    batch_id: str
    accepted: int = Field(ge=0)
    duplicates: int = Field(ge=0)
    rejected: int = Field(ge=0)
    quarantined: list[QuarantineNotice] = Field(default_factory=list)
    replayed: bool = False


def record_identity(record: IngestRecord) -> str:
    """Deduplication key of a record within its kind.

    Events dedupe on ``event_id``. Upsert-style records (assets, inventory,
    scan runs, health) dedupe on identity *plus content*, so repeated identical
    submissions collapse while genuine updates still flow through.
    """
    data = record.data
    if isinstance(data, SecurityEvent):
        return data.event_id
    if isinstance(data, PostureFinding):
        return stable_id("rec.finding.v1", data.finding_id, data.scan_run_id)
    if isinstance(data, ScanRun):
        finished = iso_utc(data.finished_at) if data.finished_at else ""
        return stable_id("rec.scan.v1", data.scan_run_id, data.status.value, finished)
    if isinstance(data, CollectorHealth):
        return stable_id("rec.health.v1", data.collector_id, iso_utc(data.reported_at))
    if isinstance(data, InventoryItem):
        return stable_id(
            "rec.inv.v1",
            data.asset_id,
            data.item_type.value,
            data.item_key,
            data.snapshot_id,
            data.present,
            canonical_json(data.attributes),
        )
    if isinstance(data, Service):
        # Content-based (like assets): repeated identical discovery collapses, changes flow.
        return stable_id(
            "rec.service.v1", data.service_id, canonical_json(data.model_dump(mode="json"))
        )
    if isinstance(data, ServiceInstance):
        # v2: include a refresh bucket of observed_at. v1 excluded observed_at entirely, so a
        # periodic re-send of an unchanged live instance (and a state change back to an
        # earlier value) was deduplicated for the 7-day dedup window and live instances
        # looked stale. Identical re-sends within one bucket still collapse.
        bucket = int(data.observed_at.timestamp()) // INSTANCE_REFRESH_BUCKET_SECONDS
        return stable_id(
            "rec.instance.v2",
            data.instance_id,
            data.state,
            data.present,
            canonical_json(data.model_dump(mode="json", exclude={"observed_at"})),
            bucket,
        )
    if isinstance(data, Asset):
        # Full content (including last_seen): collectors send asset upserts at most
        # every few minutes or on change; ReplacingMergeTree collapses history.
        content = data.model_dump(mode="json")
        return stable_id("rec.asset.v1", data.asset_id, canonical_json(content))
    raise TypeError(f"unsupported record type {type(data).__name__}")


def summarize_reason(exc: Exception, limit: int = 512) -> MediumStr:
    """Compact, secret-free validation error summary for quarantine records."""
    text = str(exc).replace("\n", " | ")
    return text[:limit]
