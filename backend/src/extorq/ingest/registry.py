"""Producer registry: token authentication and per-record authorization.

``var/secrets/producers.json`` (generated by ``make bootstrap``) lists each
producer with the SHA-256 of its bearer token and what it may send (PLAN §4.3).
The gateway never stores or logs plaintext tokens.

Authentication compares the SHA-256 digest of the presented token against
every registered digest with :func:`hmac.compare_digest` (no early exit), so
response timing does not reveal which producer, if any, matched.

Authorization (per record):

* ``kind`` must be in ``allowed_kinds``;
* the asset id must match one of ``allowed_asset_patterns`` (``fnmatchcase``);
* source types must match ``allowed_source_types`` for records that carry them
  (``event.source.source_type`` and every ``collector_health.source_types`` entry);
  exception: ``extorq.collector.gap_detected`` events (catalog source
  ``extorq.pipeline``) are allowed when ``attributes.source_type`` names a
  source type the producer is authorized for (B1 interface note 4.1);
* ``scan_run.producer_id`` must equal the authenticated producer.
"""

from __future__ import annotations

import hashlib
import hmac
import json
import threading
import time
from fnmatch import fnmatchcase
from pathlib import Path

from pydantic import BaseModel, ConfigDict, Field

from extorq.contracts.common import Identifier, Sha256Hex
from extorq.contracts.event import SecurityEvent
from extorq.contracts.health import CollectorHealth
from extorq.contracts.ingest import IngestRecord, RecordKind
from extorq.contracts.scan import ScanRun


GAP_EVENT_TYPE = "extorq.collector.gap_detected"
GAP_SOURCE_TYPE = "extorq.pipeline"


class ProducerEntry(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)

    producer_id: Identifier
    token_sha256: Sha256Hex
    allowed_kinds: list[RecordKind] = Field(min_length=1)
    allowed_source_types: list[str] = Field(min_length=1)
    allowed_asset_patterns: list[str] = Field(min_length=1)

    def kind_allowed(self, kind: str) -> bool:
        return kind in {k.value for k in self.allowed_kinds}

    def asset_allowed(self, asset_id: str) -> bool:
        return any(fnmatchcase(asset_id, pattern) for pattern in self.allowed_asset_patterns)

    def source_type_allowed(self, source_type: str) -> bool:
        return any(fnmatchcase(source_type, pattern) for pattern in self.allowed_source_types)

    def authorize(self, record: IngestRecord) -> str | None:
        """Return a denial reason for ``record`` or ``None`` when it is authorized."""
        kind = record.kind
        if not self.kind_allowed(kind):
            return f"kind_not_allowed:{kind}"
        data = record.data
        asset_id = data.asset_id
        if not self.asset_allowed(asset_id):
            return f"asset_not_allowed:{asset_id}"
        if isinstance(data, SecurityEvent):
            source_type = data.source.source_type.value
            if source_type == GAP_SOURCE_TYPE and data.event_type == GAP_EVENT_TYPE:
                # The catalog only allows extorq.pipeline as the source of gap events,
                # but gaps are detected by collectors. Narrow rule: a producer may report
                # a gap only for a source type it is itself authorized to send.
                affected = data.attributes.get("source_type")
                if not isinstance(affected, str) or not self.source_type_allowed(affected):
                    return "gap_event_for_unauthorized_source_type"
            elif not self.source_type_allowed(source_type):
                return f"source_type_not_allowed:{source_type}"
        elif isinstance(data, CollectorHealth):
            for source_type in data.source_types:
                if not self.source_type_allowed(source_type):
                    return f"source_type_not_allowed:{source_type}"
        elif isinstance(data, ScanRun) and data.producer_id != self.producer_id:
            return "scan_run_producer_mismatch"
        return None


class RegistryDocument(BaseModel):
    model_config = ConfigDict(extra="forbid")

    version: int = 1
    producers: list[ProducerEntry] = Field(min_length=1)


class RegistryError(RuntimeError):
    """producers.json missing or invalid (message never includes token material)."""


def token_digest(token: str) -> str:
    return hashlib.sha256(token.encode("utf-8")).hexdigest()


class ProducerRegistry:
    """Loads producers.json and reloads it when the file changes (checked every few seconds)."""

    def __init__(self, path: Path, *, reload_interval: float = 5.0) -> None:
        self.path = path
        self.reload_interval = reload_interval
        self._lock = threading.Lock()
        self._entries: tuple[ProducerEntry, ...] = ()
        self._mtime: float | None = None
        self._checked_at = 0.0
        self._load()

    @classmethod
    def from_entries(cls, entries: list[ProducerEntry]) -> ProducerRegistry:
        registry = cls.__new__(cls)
        registry.path = Path("/dev/null")
        registry.reload_interval = float("inf")
        registry._lock = threading.Lock()
        registry._entries = tuple(entries)
        registry._mtime = None
        registry._checked_at = float("inf")
        return registry

    def _load(self) -> None:
        try:
            stat = self.path.stat()
            raw = self.path.read_text(encoding="utf-8")
        except OSError as exc:
            raise RegistryError(f"producer registry unreadable: {type(exc).__name__}") from None
        try:
            document = RegistryDocument.model_validate(json.loads(raw))
        except (ValueError, TypeError) as exc:
            raise RegistryError(f"producer registry invalid: {type(exc).__name__}") from None
        ids = [entry.producer_id for entry in document.producers]
        if len(ids) != len(set(ids)):
            raise RegistryError("producer registry contains duplicate producer ids")
        with self._lock:
            self._entries = tuple(document.producers)
            self._mtime = stat.st_mtime
            self._checked_at = time.monotonic()

    def _maybe_reload(self) -> None:
        if time.monotonic() - self._checked_at < self.reload_interval:
            return
        self._checked_at = time.monotonic()
        try:
            mtime = self.path.stat().st_mtime
        except OSError:
            return  # keep serving the last good registry
        if mtime != self._mtime:
            try:
                self._load()
            except RegistryError:
                return  # keep the last good registry; the error is visible at startup

    @property
    def producer_ids(self) -> list[str]:
        return [entry.producer_id for entry in self._entries]

    def get(self, producer_id: str) -> ProducerEntry | None:
        for entry in self._entries:
            if entry.producer_id == producer_id:
                return entry
        return None

    def authenticate(self, token: str | None) -> ProducerEntry | None:
        """Return the producer whose token digest matches, comparing against ALL entries."""
        self._maybe_reload()
        if not token:
            return None
        presented = token_digest(token).encode("ascii")
        match: ProducerEntry | None = None
        for entry in self._entries:
            if hmac.compare_digest(presented, entry.token_sha256.encode("ascii")):
                match = entry
        return match
